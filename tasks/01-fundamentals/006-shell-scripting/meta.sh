CATEGORY="fundamentals"
DIFFICULTY="intermediate"
ENVIRON="both"
DESCRIPTION="You keep needing to know how many regular files (not
directories) sit directly in a folder, and you're tired of typing the
same 'find' one-liner. Time to script it."
OBJECTIVE="Create an executable script named count_files.sh in the
workspace directory. When run as './count_files.sh', it must print
EXACTLY one line to stdout in the form:
  File count: N
where N is the number of regular files directly inside the workspace
directory (not counting subdirectories or files inside subdirectories).
Run 'lab check 01-fundamentals/006-shell-scripting' when done."
